def setting_type(entry, warnings):
    raw = str(entry.get("type") or "")
    name = SETTING_TYPES.get(raw)
    if name is None:
        warnings.append(f"{SETTINGS_PATH}: setting {entry['key']} has type {raw!r}, which the generator doesn't name")
        name = code(raw) if raw else ""
    if entry.get("readOnly") is True:
        name += ", read-only"
    return name


def setting_default(entry, warnings):
    raw_type = entry.get("type")
    value = entry.get("value")
    if raw_type in SECURED_TYPES:
        return "Not shown"
    if value is None:
        return "blank"
    if isinstance(value, bool):
        value = "true" if value else "false"
    value = str(value)
    if raw_type == "boolean":
        if value not in ("true", "false"):
            warnings.append(f"{SETTINGS_PATH}: toggle {entry['key']} has value {value!r}")
            return code(value)
        return "On" if value == "true" else "Off"
    if raw_type == "select":
        for option in entry.get("options") or []:
            if str(option.get("key")) == value:
                return f"**{escape_text(str(option.get('value')))}** ({code(value)})"
        warnings.append(f"{SETTINGS_PATH}: select {entry['key']} has value {value!r}, not one of its options")
        return code(value)
    if value.strip() == "":
        return "blank"
    if raw_type == "number" and re.fullmatch(r"-?\d+(\.\d+)?", value):
        return value
    return code(value)


def applies_lines(groups, setting_notes):
    """The settings that don't apply at once, for the lede, merged where the text is the same."""
    out = []
    for group in groups:
        merged = {}
        for entry in group["config"]:
            note = setting_notes.get((group["key"], entry["key"]))
            if note and note.get("applies"):
                merged.setdefault(note["applies"], []).append(entry["label"])
        for applies, labels in merged.items():
            names = [f"**{escape_text(group['name'])} › {escape_text(labels[0])}**"]
            names += [f"**{escape_text(label)}**" for label in labels[1:]]
            verb = "applies" if len(labels) == 1 else "apply"
            out.append(f"  - {join_labels(names)} {verb} {applies}")
    return out


def render_settings(groups, setting_notes, tag, warnings):
    total = sum(len(g["config"]) for g in groups)
    lines = frontmatter(
        "All settings", SETTINGS_ORDER,
        "Every setting in Flow v5's Admin › Settings, by group, with its key, type, default and description.",
        tag,
    )
    lines += [marker(tag), "", "# All settings", ""]
    lines += [
        f"This page lists every setting Flow seeds at `{tag}`: {total} settings in {len(groups)}"
        " groups, in the order **Admin › Settings** lists the groups. An admin changes them in"
        " **Admin › Settings**, or with `PATCH /api/v2/settings` and a body of"
        " `{\"<group>\": {\"<key>\": value}}`, using the group key and key below. See"
        f" [Admin]({ADMIN_LINK}).",
        "",
        "- **Restart:** none needed. A saved setting applies without a restart. The exceptions:",
    ]
    exceptions = applies_lines(groups, setting_notes)
    lines += exceptions if exceptions else ["  - None."]
    lines += [
        "- **Default:** the value on a new install. An upgraded install keeps the values it had."
        " A toggle's default is On or Off; the API reads it as `true` or `false`.",
        "- **Secured:** a secured value is stored encrypted and never shown: the webapp shows"
        " **Set** when it holds one, and the API returns `*****`. Its default here is \"Not shown\".",
        "",
        "Deployment configuration, read at start, is in properties instead: see"
        " [All properties](./properties-reference).",
        "",
    ]
    for group in groups:
        lines += [f"## {group['name']}", ""]
        description = (group.get("description") or "").strip()
        intro = escape_text(description) + " " if description else ""
        lines += [f"{intro}Group key: {code(group['key'])}.", ""]
        lines += [
            "| Label | Key | Type | Default | Description |",
            "| --- | --- | --- | --- | --- |",
        ]
        for entry in group["config"]:
            parts = []
            if entry.get("description"):
                parts.append(escape_text(str(entry["description"]).strip()))
            if entry.get("type") == "select" and entry.get("options"):
                options = ", ".join(
                    f"**{escape_text(str(o.get('value')))}** ({code(o.get('key'))})" for o in entry["options"])
                parts.append(f"Options: {options}.")
            note = setting_notes.get((group["key"], entry["key"]))
            if note:
                if note.get("text"):
                    parts.append(note_markdown(note))
                # The lede lists it too; the row repeats it unless the description already says when.
                if note.get("applies") and not re.search(r"\bappl(y|ies|ied)\b", str(entry.get("description")), re.I):
                    parts.append(f"**Note:** Applies {note['applies']}")
            lines.append(
                f"| **{escape_text(str(entry['label']))}** | {code(entry['key'])} | "
                f"{setting_type(entry, warnings)} | {setting_default(entry, warnings)} | "
                f"{'<br>'.join(parts)} |"
            )
        lines.append("")
    lines += [
        "## Next steps",
        "",
        f"- [Admin]({ADMIN_LINK}): where an admin changes these settings.",
        "- [Quotas](../webapp/quotas): how the quota settings and a workspace's own quotas combine.",
        "- [All properties](./properties-reference): the deployment configuration each service reads at start.",
        "",
    ]
    return "\n".join(lines).rstrip() + "\n"


