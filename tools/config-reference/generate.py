# Markdown helpers


def escape_text(text):
    """Plain text safe in a table cell: Markdown specials escaped, pipes escaped."""
    text = text.replace("\\", "\\\\")
    text = re.sub(r"([*_\[\]])", r"\\\1", text)
    return text.replace("<", "&lt;").replace("|", "\\|")


def code(value):
    value = str(value).replace("\r\n", "\n").replace("\n", " ")
    ticks = max((len(m) for m in re.findall(r"`+", value)), default=0) + 1
    fence = "`" * ticks
    pad = " " if value.startswith("`") or value.endswith("`") else ""
    return f"{fence}{pad}{value}{pad}{fence}".replace("|", "\\|")


def comment_markdown(text):
    """A comment from a properties file as cell Markdown: its own code spans kept, property names,
    environment variables, paths and URLs put in code, everything else escaped."""
    out = []
    for part in re.split(r"(`[^`]*`)", text):
        if part.startswith("`") and part.endswith("`") and len(part) > 1:
            out.append(part.replace("|", "\\|"))
            continue
        pos = 0
        for m in TOKEN.finditer(part):
            token = m.group(0)
            trail = ""
            while token and token[-1] in ".,;:":
                trail = token[-1] + trail
                token = token[:-1]
            if m.lastgroup == "prop" and any(len(s) < 2 and s != "*" for s in token.split("=")[0].split(".")):
                continue  # "e.g" and the like
            out.append(escape_text(part[pos:m.start()]))
            out.append(code(token) + escape_text(trail))
            pos = m.end()
        out.append(escape_text(part[pos:]))
    return "".join(out)


def note_markdown(entry):
    label = "Warning" if entry.get("level") == "warning" else "Note"
    text = entry["text"].replace("\n", " ").replace("|", "\\|")
    return f"**{label}:** {text}"


def heading_slug(text):
    """GitHub's heading slugger, as rehype-slug uses it on the website."""
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    slug = text.strip().lower()
    slug = re.sub(r"[^\w\- ]", "", slug)
    return slug.replace(" ", "-")


def frontmatter(title, order, description, tag):
    return ["---", f"title: {title}", f"order: {order}", f"description: {description}",
            f'verified: "{tag}"', "---", ""]


def marker(tag):
    return f"{MARKER} from flow.service.workflow {tag}. Don't edit by hand. -->"


def join_labels(labels):
    if len(labels) == 1:
        return labels[0]
    return ", ".join(labels[:-1]) + " and " + labels[-1]


