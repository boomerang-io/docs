def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--flow-repo", required=True, help="a clone of boomerang-io/flow.service.workflow")
    parser.add_argument("--tag", required=True, help="the Flow release tag the docs describe")
    parser.add_argument("--out", default=str(DEFAULT_OUT), help="output folder (default: flow/hosting)")
    parser.add_argument("--notes", default=str(DEFAULT_NOTES),
                        help="notes file (default: tools/config-reference/notes.json)")
    parser.add_argument("--hand-page", default=str(DEFAULT_HAND_PAGE),
                        help="the hand-kept page to compare (default: flow/hosting/configuration-reference.md)")
    parser.add_argument("--check", action="store_true",
                        help="write nothing; exit 1 if the pages differ from what the tag generates")
    args = parser.parse_args(argv)

    out = Path(args.out)
    warnings, applied_props, applied_settings = [], [], []
    counts = {"suppressed": []}
    try:
        notes = json.loads(Path(args.notes).read_text())
        services = []
        for service, heading, image, path in SERVICES:
            props = parse_properties(git_show(args.flow_repo, args.tag, path), path)
            apply_property_notes(service, props, notes, warnings, applied_props)
            services.append((service, heading, image, props))

        groups = load_settings(git_show(args.flow_repo, args.tag, SETTINGS_PATH))
        if not SETTINGS_SORT.search(git_show(args.flow_repo, args.tag, SETTINGS_UI_PATH)):
            warnings.append(f"{SETTINGS_UI_PATH} no longer sorts groups with sortBy(settings, g => g.name):"
                            " check the order Admin › Settings lists them in")
        setting_notes = apply_setting_notes(groups, notes, warnings, applied_settings)

        pages = {
            PROPERTIES_PAGE: render_properties(services, args.tag, counts),
            SETTINGS_PAGE: render_settings(groups, setting_notes, args.tag, warnings),
        }
    except (GeneratorError, json.JSONDecodeError, KeyError, OSError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1

    link_errors = check_links(pages, out)
    for message in link_errors:
        print(f"error: {message}", file=sys.stderr)
    if link_errors:
        return 1

    hand = Path(args.hand_page)
    missing, example_only, spring = ([], [], [])
    if hand.exists():
        missing, example_only, spring = compare_hand_page(hand.read_text(), services)
    else:
        warnings.append(f"{hand} not found; nothing compared")

    for message in warnings:
        print(f"warning: {message}", file=sys.stderr)
    rel = hand.name
    for name, number in missing:
        print(f"warning: {rel}:{number} names {name}, which isn't in application.properties at {args.tag}",
              file=sys.stderr)
    for name, number in example_only:
        print(f"note: {rel}:{number} names {name}, which application.properties has only as a"
              f" commented-out example", file=sys.stderr)
    for name, number in spring:
        print(f"note: {rel}:{number} names {name}, labelled a {SPRING_LABEL}, so it isn't in"
              f" application.properties", file=sys.stderr)

    if args.check:
        changed = [n for n, text in pages.items() if not (out / n).exists() or (out / n).read_text() != text]
        for name in changed:
            print(f"differs: {out / name}")
        return 1 if changed else 0

    out.mkdir(parents=True, exist_ok=True)
    for name, text in pages.items():
        (out / name).write_text(text)

    summary = ", ".join(f"{len(props)} {service}" for service, _, _, props in services)
    print(
        f"Wrote {PROPERTIES_PAGE} and {SETTINGS_PAGE} to {out} from {args.tag}: "
        f"{sum(len(p) for *_, p in services)} properties ({summary}); "
        f"{sum(len(g['config']) for g in groups)} settings in {len(groups)} groups; "
        f"{len(counts['suppressed'])} secret defaults shown as \"{SET_YOUR_OWN}\"; "
        f"notes on {len(set(applied_props))} properties and {len(set(applied_settings))} settings; "
        f"{len(missing)} {'property' if len(missing) == 1 else 'properties'} named on {hand.name}"
        f" but not in the source."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
