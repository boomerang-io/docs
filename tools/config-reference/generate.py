# Reading the source


def git_show(repo, tag, path):
    result = subprocess.run(
        ["git", "-C", str(repo), "show", f"{tag}:{path}"],
        capture_output=True, text=True,
    )
    if result.returncode != 0:
        raise GeneratorError(f"git show {tag}:{path} failed: {result.stderr.strip()}")
    return result.stdout


class Prop:
    def __init__(self, key, value, line, example):
        self.key = key
        self.value = value
        self.line = line
        self.example = example  # only a commented-out example in the file
        self.comment = None     # the comment block right above it, cleaned
        self.shares = None      # the key whose comment covers this property too
        self.secret = False
        self.notes = []


def clean_comment_lines(lines):
    """The comment block as description text: project codes and headings dropped."""
    cleaned = []
    for line in lines:
        line = PAREN_CODE.sub("", line)
        line = LEADING_CODE.sub("", line).strip()
        if line and not HISTORY_LINE.match(line):
            cleaned.append(line)
    # A heading is a short line in title form, such as "Proxy Settings" or "Error Management".
    # Only the lines after the block's last heading describe the property below it.
    start = 0
    for i, line in enumerate(cleaned):
        previous = cleaned[i - 1] if i else None
        if (len(line.split()) <= 5 and line[:1].isupper() and "=" not in line
                and not re.search(r"[.:;,!?]$", line)
                and (previous is None or re.search(r"[.:;!?]$", previous))):
            start = i + 1
    text = " ".join(cleaned[start:]).strip()
    return text or None


def segments(key):
    return key.split(".")


def related(a, b):
    """Whether a comment over property a plausibly covers property b in the same run of lines:
    the same parent, or the same shape differing in one segment (limit/request)."""
    sa, sb = segments(a), segments(b)
    if sa[:-1] == sb[:-1]:
        return True
    return len(sa) == len(sb) and sum(x != y for x, y in zip(sa, sb)) == 1


def parse_properties(text, path):
    """Every property in a properties file, in file order, with the comment above it.

    A commented-out `key=value` line is an example property when no live line sets that key, and
    is ignored when one does (it shows an alternative value). A run is a set of property lines with
    no comment or blank line between them; a property in a run without a comment of its own shares
    the comment of the nearest earlier property in the run that it is related to.
    """
    raw = text.splitlines()
    live = set()
    for line in raw:
        s = line.strip()
        if s and s[0] not in "#!" and "=" in s:
            live.add(s.split("=", 1)[0].strip())

    props, block, run = [], [], []
    seen = {}

    def add(key, value, number, example):
        nonlocal block, run
        if key in seen:
            if not example:
                raise GeneratorError(f"{path}:{number}: {key} is set twice")
            return
        prop = Prop(key, value, number, example)
        prop.comment = clean_comment_lines(block)
        if prop.comment is None:
            for earlier in reversed(run):
                if (earlier.comment or earlier.shares) and related(earlier.key, key):
                    prop.shares = earlier.shares or earlier.key
                    break
        block = []
        run.append(prop)
        props.append(prop)
        seen[key] = prop

    for number, line in enumerate(raw, start=1):
        s = line.strip()
        if not s:
            block, run = [], []
            continue
        if s[0] in "#!":
            m = COMMENTED_PROPERTY.match(s)
            if m:
                key = m.group(1)
                if key in live:
                    run = []  # an alternative value for a live property
                    continue
                add(key, m.group(2).strip(), number, True)
                continue
            if run:
                run = []
            block.append(s.lstrip("#!").strip())
            continue
        if "=" not in s:
            raise GeneratorError(f"{path}:{number}: not a key=value line: {s}")
        key, value = s.split("=", 1)
        add(key.strip(), value.strip(), number, False)
    return props


def load_settings(text):
    data = json.loads(text)
    if not isinstance(data, dict) or not isinstance(data.get("documents"), list):
        raise GeneratorError(f"{SETTINGS_PATH}: expected {{\"documents\": [...]}}")
    groups = []
    for doc in data["documents"]:
        for field in ("key", "name", "config"):
            if field not in doc:
                raise GeneratorError(f"{SETTINGS_PATH}: a settings group has no {field}")
        for entry in doc["config"]:
            if "key" not in entry or "label" not in entry:
                raise GeneratorError(f"{SETTINGS_PATH}: group {doc['key']}: an entry has no key or label")
        groups.append(doc)
    # Admin > Settings: sortBy(settings, (settingsGroup) => settingsGroup.name).
    return sorted(groups, key=lambda g: str(g["name"]).encode("utf-16-be"))


