#!/usr/bin/env python3
"""Generate Flow's properties and settings reference pages from flow.service.workflow at a tag.

Reads, with `git show <tag>:<path>`:
  - service-core/src/main/resources/application.properties and
    service-dispatcher/src/main/resources/application.properties (the properties);
  - service-core/src/main/resources/seed/settings.json (the settings);
  - client-web/src/Features/Settings/Settings.tsx (to confirm the order Admin > Settings lists groups in).

Writes flow/hosting/properties-reference.md and flow/hosting/settings-reference.md with the
hand-kept notes in notes.json, checks every link the pages carry, and lists each property that
flow/hosting/configuration-reference.md names but the tag's application.properties doesn't have.
See tools/config-reference/README.md.

Python 3.9+, standard library only.
"""

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

DOCS_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUT = DOCS_ROOT / "flow" / "hosting"
DEFAULT_NOTES = Path(__file__).resolve().parent / "notes.json"
DEFAULT_HAND_PAGE = DEFAULT_OUT / "configuration-reference.md"

# (notes key, heading, image, properties file); the heading lower-cased reads as "core" and
# "the dispatcher" in a sentence.
SERVICES = [
    ("core", "Core", "service-core", "service-core/src/main/resources/application.properties"),
    ("dispatcher", "Dispatcher", "service-dispatcher",
     "service-dispatcher/src/main/resources/application.properties"),
]
IN_A_SENTENCE = {"core": "core", "dispatcher": "the dispatcher"}
SETTINGS_PATH = "service-core/src/main/resources/seed/settings.json"
SETTINGS_UI_PATH = "client-web/src/Features/Settings/Settings.tsx"
# Admin > Settings lists the groups with lodash sortBy on the group's name: a plain string
# comparison by UTF-16 code unit. The generator checks the expression is still there.
SETTINGS_SORT = re.compile(r"sortBy\(\s*settings\s*,\s*\(\s*(\w+)\s*\)\s*=>\s*\1\.name\s*\)")

PROPERTIES_PAGE = "properties-reference.md"
SETTINGS_PAGE = "settings-reference.md"
# Menu positions in flow/hosting/: after configuration-reference (4), before sign-in (7).
PROPERTIES_ORDER = 5
SETTINGS_ORDER = 6
MARKER = "<!-- Generated by tools/config-reference/generate.py"

SET_YOUR_OWN = "(set your own)"
CONFIGURING_LINK = "../hosting/configuring#set-the-required-configuration"
ADMIN_LINK = "../webapp/administer#settings"

# A property is a secret when its key says so, or its default carries credentials in a URI.
SECRET_PREFIXES = ("flow.encrypt.", "mongo.encrypt.", "flow.security.tokens.")
SECRET_SEGMENT = re.compile(r"(^|-)(token|secret|salt|password|key|hash|otc|code|value)$")
URI_CREDENTIALS = re.compile(r"://[^/\s:@]+:[^/\s@]+@")

# Settings field types, named as Admin > Settings renders them
# (client-web/src/Features/Settings/SettingsSection/SettingsSection.tsx and DynamicFormik).
SETTING_TYPES = {
    "boolean": "Toggle",
    "number": "Number",
    "text": "Text",
    "textarea": "Text area",
    "secured": "Secured",
    "password": "Secured",
    "select": "Select",
}
SECURED_TYPES = {"secured", "password"}

COMMENTED_PROPERTY = re.compile(r"^[#!]\s*([a-z][A-Za-z0-9_\-\[\]<>]*(?:\.[A-Za-z0-9_\-\[\]<>]+)+)\s*=(.*)$")
PLACEHOLDER = re.compile(r"^\$\{([^:}]+)(?::([^}]*))?\}$")

# Internal project codes in comments: "(E8.2a)", "(merged from service-engine, E8.2a)", "(DD-02)",
# a leading "T6-1:", and the "Merged from service-engine" history lines.
CODE = r"[A-Z]{1,2}-?\d+(?:[.\-]\d+)*[a-z]?\d*"
PAREN_CODE = re.compile(r"\s*\((?:[^()]*?,\s*)?" + CODE + r"\)")
LEADING_CODE = re.compile(r"^" + CODE + r":\s*")
HISTORY_LINE = re.compile(r"^Merged from service-engine\b")

# Tokens put in code formatting when a property comment is rendered.
TOKEN = re.compile(
    r"(?P<url>https?://[^\s)`]+)"
    r"|(?P<placeholder>\$\{[^}\s]+\})"
    r"|(?P<path>(?<![\w/.\-])[a-z][\w\-]*(?:/[\w\-.]+)+\.(?:java|ya?ml|md|properties|json|js))"
    r"|(?P<prop>(?<![\w/.\-])[a-z][A-Za-z0-9\-]*"
    r"(?:\.(?:[A-Za-z0-9\-]+(?:\[\d+\])?|\*|<[a-z]+>|\{[a-z]+\}))+(?:=[^\s,;)]+)?)"
    r"|(?P<env>(?<![\w$])(?:_?[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+_?|_[A-Z][A-Z0-9]+)(?!\w))"
    r"|(?P<snake>(?<![\w.\-/])[a-z][a-z0-9]*_[a-z0-9_]*(?!\w))"
    r"|(?P<route>(?<![\w/.:])/[A-Za-z0-9_{}*\-.]+(?:/[A-Za-z0-9_{}*\-.]+)*)"
)

# A property name in a code span of the hand page.
HAND_PROPERTY = re.compile(
    r"[a-z][A-Za-z0-9\-]*(?:\.(?:[A-Za-z0-9\-]+(?:\[\d+\])?|\*|<[a-z]+>))+")
# A hand-page row with this label names a property Spring Boot reads, not one in Flow's files.
SPRING_LABEL = "Spring Boot property"
NOT_A_PROPERTY = re.compile(r"\.(md|properties|json|ya?ml|java|tsx?|png|svg|com|io|org|net|local)$")


class GeneratorError(Exception):
    pass


