def strip_code(text):
    """Text with fenced code blocks and code spans blanked out, line count kept."""
    text = re.sub(r"(?ms)^```.*?^```", lambda m: "\n" * m.group(0).count("\n"), text)
    return re.sub(r"`+[^`\n]*`+", "", text)


def page_anchors(text):
    anchors, counts = set(), {}
    for line in strip_code(text).splitlines():
        m = re.match(r"^#{1,6}\s+(.*?)\s*#*\s*$", line)
        if not m:
            continue
        slug = heading_slug(m.group(1))
        n = counts.get(slug, 0)
        anchors.add(slug if n == 0 else f"{slug}-{n}")
        counts[slug] = n + 1
    return anchors


def check_links(pages, out):
    """Every relative link in the generated pages resolves to a page, and its anchor to a heading."""
    out_dir = out.resolve()

    def read(path):
        if path.parent == out_dir and path.name in pages:
            return pages[path.name]
        if path.is_file():
            return path.read_text() if path.suffix == ".md" else ""
        return None

    errors = []
    for name, text in pages.items():
        for target in re.findall(r"\]\(([^)\s]+)\)", strip_code(text)):
            if re.match(r"^[a-z]+:", target):
                continue
            path, _, anchor = target.partition("#")
            if path:
                base = (out_dir / path).resolve()
                candidates = [base] if base.suffix else [base.with_name(base.name + ".md"), base / "index.md"]
                target_text = next((t for t in map(read, candidates) if t is not None), None)
                if target_text is None:
                    errors.append(f"{name}: link {target} doesn't resolve to a page")
                    continue
            else:
                target_text = text
            if anchor and anchor not in page_anchors(target_text):
                errors.append(f"{name}: link {target}: no heading with the anchor #{anchor}")
    return errors


def hand_page_properties(text):
    """The property names the hand page puts in code spans, with `.suffix` shorthand expanded
    against the previous full name on the same line."""
    text = re.sub(r"(?s)^---\n.*?\n---\n", "", text)
    text = re.sub(r"(?s)<!--.*?-->", "", text)
    names = []
    for number, line in enumerate(text.splitlines(), start=1):
        last = None
        spring = SPRING_LABEL in line
        for span in re.findall(r"`([^`]+)`", line):
            span = span.strip().split("=", 1)[0]
            if span.startswith(".") and last:
                name = ".".join(segments(last)[:-1]) + span
            elif HAND_PROPERTY.fullmatch(span) and not NOT_A_PROPERTY.search(span):
                name = last = span
            else:
                continue
            if name not in [n for n, _, _ in names]:
                names.append((name, number, spring))
    return names


def name_regex(name):
    out = ""
    for piece in re.split(r"(<[a-z]+>|\*)", name):
        if piece == "*":
            out += ".+"
        elif re.fullmatch(r"<[a-z]+>", piece or ""):
            out += r"[^.]+"
        else:
            out += re.escape(piece)
    return re.compile(out + r"$")


def compare_hand_page(text, services):
    live, examples = set(), set()
    for _, _, _, props in services:
        for p in props:
            (examples if p.example else live).add(p.key)
    missing, example_only, spring = [], [], []
    for name, number, labelled in hand_page_properties(text):
        rx = name_regex(name)
        if any(rx.match(k) for k in live):
            continue
        if any(rx.match(k) for k in examples):
            example_only.append((name, number))
        elif labelled:
            spring.append((name, number))
        else:
            missing.append((name, number))
    return missing, example_only, spring


