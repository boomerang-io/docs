    total = sum(len(props) for _, _, _, props in services)
    lines = frontmatter(
        "All properties", PROPERTIES_ORDER,
        "Every property in Flow v5 core's and dispatcher's application.properties, with its "
        "environment variable, default and description.",
        tag,
    )
    lines += [marker(tag), "", "# All properties", ""]
    per_service = " and ".join(f"{len(props)} for {IN_A_SENTENCE[service]}" for service, _, _, props in services)
    lines += [
        f"This page lists every property in the `application.properties` files of Flow's core and"
        f" dispatcher images at `{tag}`: {total} properties, {per_service}. It's the complete list."
        " For the properties most deployments set, start with the"
        " [Configuration reference](./configuration-reference).",
        "",
        "- **Restart:** each service reads its properties when it starts, so a changed property"
        " takes effect only when you restart that service. Behaviour an admin changes while Flow"
        " runs is a setting: see [All settings](./settings-reference).",
        "- **Environment variable:** derived, not listed in the file. Spring's relaxed binding reads"
        " each property from an environment variable named for it in upper case, with dots, dashes"
        " and list indexes turned into underscores, and the variable overrides the file:"
        " `flow.encrypt.secret` becomes `FLOW_ENCRYPT_SECRET`.",
        f"- **Default:** the value in the file. A secret's default is never shown: its row says"
        f" \"{SET_YOUR_OWN}\". Keep secrets in a Kubernetes Secret, as"
        f" [Set the required configuration]({CONFIGURING_LINK}) shows. \"Not set\" marks a property"
        " the file shows only as a commented-out example.",
        "- **Description:** the comment above the property in the file, with internal project codes"
        " removed. \"See\" names the property whose comment covers this one too. A **Note** is added"
        " by the docs, from Flow's specifications and changelog.",
        "",
        "Rows are sorted by property, so properties that share a prefix sit together.",
        "",
    ]
    for service, heading, image, props in services:
        lines += [
            f"## {heading}",
            "",
            f"Set these on {IN_A_SENTENCE[service]} (`{image}`). The file is"
            f" `{image}/src/main/resources/application.properties`.",
            "",
            "| Property | Environment variable | Default | Description |",
            "| --- | --- | --- | --- |",
        ]
        for prop in sorted(props, key=lambda p: (p.key.casefold(), p.key)):
            secret = is_secret(prop)
            default = default_cell(prop, secret)
            if default == SET_YOUR_OWN:
                counts["suppressed"].append(f"{service}:{prop.key}")
            lines.append(
                f"| {code(prop.key)} | {code(env_name(prop.key))} | {default} | "
                f"{description_cell(prop, secret)} |"
            )
        lines.append("")
    lines += [
        "## Next steps",
        "",
        "- [Configuring](./configuring): set up each image step by step.",
        "- [Configuration reference](./configuration-reference): the properties most deployments set, by area.",
        "- [All settings](./settings-reference): what an admin changes in **Admin › Settings**, without a restart.",
        "",
    ]
    return "\n".join(lines).rstrip() + "\n"


