def env_name(key):
    """Spring relaxed binding: upper case, with dots, dashes and list indexes as underscores."""
    name = re.sub(r"\[(\d+)\]", r"_\1", key).replace("<", "").replace(">", "")
    return re.sub(r"[.\-]", "_", name).upper()


def is_secret(prop):
    key = prop.key
    if prop.secret or key.startswith(SECRET_PREFIXES):
        return True
    # A switch such as trust-forwarded-token=false names a token but holds none.
    if SECRET_SEGMENT.search(segments(key)[-1].lower()) and prop.value.strip() not in ("true", "false"):
        return True
    return bool(URI_CREDENTIALS.search(prop.value))


def default_cell(prop, secret):
    if prop.example:
        return SET_YOUR_OWN if secret else "not set"
    value = prop.value.strip()
    m = PLACEHOLDER.match(value)
    if m:
        name, fallback = m.group(1), m.group(2) or ""
        if name == env_name(prop.key):
            value = fallback
        elif re.fullmatch(r"[A-Z][A-Z0-9_]*", name):
            text = f"Same as `{name}`"
            if fallback:
                text += ", else " + (SET_YOUR_OWN if secret else code(fallback))
            return text
    if secret:
        return SET_YOUR_OWN
    return code(value) if value else "blank"


def description_cell(prop, secret):
    parts = []
    if prop.comment:
        parts.append(comment_markdown(prop.comment))
    elif prop.shares:
        parts.append(f"See {code(prop.shares)}.")
    if prop.example:
        if secret:
            parts.append("Commented out in the file, as an example.")
        else:
            parts.append(f"Commented out in the file, as an example: {code(prop.key + '=' + prop.value)}.")
    parts += [note_markdown(n) for n in prop.notes]
    return "<br>".join(parts)


