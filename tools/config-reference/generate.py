def pattern_matches(pattern, key):
    if pattern.endswith("*"):
        return key.startswith(pattern[:-1])
    return key == pattern


def apply_property_notes(service, props, notes, warnings, applied):
    by_key = {p.key: p for p in props}
    for pattern, entry in notes.get("properties", {}).get(service, {}).items():
        if pattern.startswith("_"):
            continue
        matched = [p for p in props if pattern_matches(pattern, p.key)]
        if not matched:
            warnings.append(f"notes.json: properties.{service}: {pattern} isn't a property in "
                            f"{service}'s application.properties")
            continue
        same_as = entry.get("sameAs")
        if same_as and same_as not in by_key:
            warnings.append(f"notes.json: properties.{service}.{pattern}: sameAs {same_as} isn't a "
                            f"property in {service}'s application.properties")
            same_as = None
        if same_as and not by_key[same_as].comment:
            same_as = by_key[same_as].shares or same_as
        for prop in matched:
            if same_as and prop.key != same_as:
                if prop.comment:
                    warnings.append(f"notes.json: properties.{service}.{pattern}: {prop.key} has a "
                                    f"comment of its own; sameAs ignored for it")
                else:
                    prop.shares = same_as
            if entry.get("secret") is True:
                prop.secret = True
            if entry.get("text"):
                prop.notes.append(entry)
            applied.append(f"{service}:{prop.key}")


def apply_setting_notes(groups, notes, warnings, applied):
    by_group = {g["key"]: g for g in groups}
    result = {}
    for group_key, entries in notes.get("settings", {}).items():
        if group_key.startswith("_"):
            continue
        group = by_group.get(group_key)
        if group is None:
            warnings.append(f"notes.json: settings: {group_key} isn't a settings group in {SETTINGS_PATH}")
            continue
        keys = {e["key"] for e in group["config"]}
        for key, entry in entries.items():
            if key not in keys:
                warnings.append(f"notes.json: settings.{group_key}: {key} isn't a setting in group {group_key}")
                continue
            result[(group_key, key)] = entry
            applied.append(f"{group_key}:{key}")
    return result


