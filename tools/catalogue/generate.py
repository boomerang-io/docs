def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--flow-repo", required=True, help="a clone of boomerang-io/flow.service.workflow")
    parser.add_argument("--tag", required=True, help="the Flow release tag the docs describe")
    parser.add_argument("--out", default=str(DEFAULT_OUT), help="output folder (default: flow/catalogue)")
    parser.add_argument("--notes", default=str(DEFAULT_NOTES), help="notes file (default: tools/catalogue/notes.json)")
    parser.add_argument("--check", action="store_true",
                        help="write nothing; exit 1 if the pages differ from what the tag generates")
    args = parser.parse_args(argv)

    out = Path(args.out)
    warnings, applied, skipped, used = [], [], [], []
    try:
        notes = json.loads(Path(args.notes).read_text())
        catalogue = load_catalogue(args.flow_repo, args.tag, notes, warnings)
        settings = json.loads(git_show(args.flow_repo, args.tag, SETTINGS_PATH))
        default_image = find_key(settings, "default.image")
        if not default_image:
            warnings.append(f"no default.image in {SETTINGS_PATH} at {args.tag}")
        artifact_image = property_value(
            git_show(args.flow_repo, args.tag, DISPATCHER_PROPERTIES), "flow.dispatcher.artifact.image")

        grouped = {}
        for item in catalogue.values():
            grouped.setdefault(item["latest"]["category"], []).append(item)
        for items in grouped.values():
            items.sort(key=by_display_name)
        ordered = palette_order(grouped)
        check_notes(notes, catalogue, grouped)
        check_usage(notes, catalogue, warnings)

        pages = {"overview.md": render_overview(ordered, grouped, notes, args.tag, default_image)}
        for order, category in enumerate(ordered, start=2):
            name = f"{page_slug(category)}.md"
            if name in pages or name == "index.md":
                raise CatalogueError(f"category {category!r} collides with page {name}")
            pages[name] = render_category(category, order, grouped[category], notes, args.tag,
                                          default_image, artifact_image, applied, skipped, used)
    except (CatalogueError, json.JSONDecodeError, KeyError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1

    stale = [
        p for p in sorted(out.glob("*.md"))
        if p.name not in pages and p.name != "index.md" and MARKER in p.read_text()
    ]
    if args.check:
        changed = [n for n, text in pages.items()
                   if not (out / n).exists() or (out / n).read_text() != text]
        for name in changed:
            print(f"differs: {out / name}")
        for path in stale:
            print(f"stale: {path}")
        return 1 if changed or stale else 0

    out.mkdir(parents=True, exist_ok=True)
    for name, text in pages.items():
        (out / name).write_text(text)
    for path in stale:
        path.unlink()
        print(f"removed {path}")

    for message in warnings + skipped:
        print(f"warning: {message}", file=sys.stderr)
    total = len(catalogue)
    shown = sum(1 for i in catalogue.values() if in_palette(i))
    revisions = sum(len(i["revisions"]) for i in catalogue.values())
    print(
        f"Wrote {len(pages)} pages to {out} from {args.tag}: {total} tasks ({shown} in the palette)"
        f" in {len(ordered)} categories, {revisions} revisions; {len(applied)} task notes applied;"
        f" {count_phrase(len(used), 'task')} with an example or common problems."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
