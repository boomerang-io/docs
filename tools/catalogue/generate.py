# Markdown helpers


def cell(text):
    """Text for a table cell, verbatim but safe: pipes escaped, line breaks kept."""
    if text is None:
        return ""
    text = str(text).replace("\r\n", "\n").strip()
    text = text.replace("|", "\\|").replace("<", "&lt;")
    return re.sub(r"\n+", "<br>", text)


def prose(text):
    text = (text or "").replace("\r\n", "\n").strip()
    return text.replace("<", "&lt;")


def md_cell(text):
    """Hand-written Markdown for a table cell: pipes escaped, line breaks kept, nothing else."""
    text = str(text or "").replace("\r\n", "\n").strip().replace("|", "\\|")
    return re.sub(r"\n+", "<br>", text)


def fenced(text, lang):
    text = (text or "").replace("\r\n", "\n").strip("\n")
    ticks = max([3] + [len(m) + 1 for m in re.findall(r"`{3,}", text)])
    fence = "`" * ticks
    return [f"{fence}{lang or 'text'}", text, fence]


def code(value, in_table=True):
    value = str(value).replace("\r\n", "\n").replace("\n", " ↵ ")
    ticks = max((len(m) for m in re.findall(r"`+", value)), default=0) + 1
    fence = "`" * ticks
    pad = " " if value.startswith("`") or value.endswith("`") else ""
    out = f"{fence}{pad}{value}{pad}{fence}"
    return out.replace("|", "\\|") if in_table else out


def heading_slug(text):
    """GitHub's heading slugger, as rehype-slug uses it on the website."""
    slug = text.strip().lower()
    slug = re.sub(r"[^\w\- ]", "", slug)
    return slug.replace(" ", "-")


def page_slug(category):
    return re.sub(r"[^a-z0-9]+", "-", category.lower()).strip("-")


def palette_order(categories):
    first = [c for c in categories if c.lower() == FIRST_CATEGORY]
    rest = sorted(c for c in categories if c.lower() != FIRST_CATEGORY)
    return first + rest


def by_display_name(item):
    return (item["latest"]["displayName"].casefold(), item["task"]["name"])


def in_palette(item):
    return item["task"].get("status") == "active"


# ---------------------------------------------------------------------------------------------
# Rendering


def image_line(task_type, spec, artifact_image):
    image = (spec.get("image") or "").strip()
    if task_type in ENGINE_TYPES:
        return "None. Flow runs this task itself."
    if task_type in ARTIFACT_TYPES:
        line = "The image in the dispatcher's `flow.dispatcher.artifact.image` property"
        return line + (f", `{artifact_image}` by default." if artifact_image else ".")
    if image:
        return f"`{image}`"
    if task_type == "custom":
        return "The image you set on the node."
    if task_type in DEFAULT_IMAGE_TYPES:
        return "Default task image."
    return "None set."


def param_type(param):
    raw = param.get("type") or ""
    label = FIELD_TYPES.get(raw, f"`{raw}`" if raw else "")
    if param.get("readOnly"):
        label += ", read-only"
    return label


def default_value(param):
    value = param.get("defaultValue")
    if value is None:
        return ""
    if not isinstance(value, str):
        value = json.dumps(value)
    if value.strip() == "":
        return ""
    if param.get("type") == "password" and not PARAM_REFERENCE.fullmatch(value.strip()):
        return "Set, not shown"
    return code(value)


def render_task(item, task_notes, artifact_image):
    task, latest = item["task"], item["latest"]
    spec = latest.get("spec") or {}
    lines = [f"## {latest['displayName']}", ""]
    description = prose(latest.get("description"))
    if description:
        lines += [description, ""]
    lines += [
        f"- **Slug:** `{task['name']}`",
        f"- **Type:** `{task['type']}`",
        f"- **Revision:** {latest['version']}",
        f"- **Image:** {image_line(task['type'], spec, artifact_image)}",
        "",
    ]
    for note in task_notes:
        lines += alert(note.get("level"), note["text"])

    params = spec.get("params") or []
    if params:
        lines += [
            "**Parameters**",
            "",
            "| Label | Name | Type | Required | Default | Helper text |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        for p in params:
            lines.append(
                f"| {cell(p.get('label'))} | {code(p.get('name', ''))} | {param_type(p)} | "
                f"{'Yes' if p.get('required') is True else 'No'} | {default_value(p)} | "
                f"{cell(p.get('helpertext'))} |"
            )
        lines.append("")
    else:
        lines += ["No parameters.", ""]

    results = spec.get("results") or []
    if results:
        lines += ["**Results**", "", "| Name | Description |", "| --- | --- |"]
        for r in results:
            lines.append(f"| {code(r.get('name', ''))} | {cell(r.get('description'))} |")
        lines.append("")
    else:
        lines += ["No results.", ""]
    return lines


def render_usage(slug, usage, item, default_image, skipped):
    """The task's "Example" and "Common problems" subsections, from notes.json's usage."""
    labels = {p.get("name"): p.get("label") or p.get("name")
              for p in (item["latest"].get("spec") or {}).get("params") or []}
    lines = []
    example = usage.get("example")
    if example:
        lines += ["### Example", ""]
        note = example.get("note")
        if note and gated(note, default_image, slug, "example note", skipped):
            lines += alert(note.get("level"), note["text"])
        lines += [example["scenario"].strip(), ""]
        rows = example.get("params") or []
        if rows:
            lines += ["| Field | Value |", "| --- | --- |"]
            for row in rows:
                field = row.get("field") or f"**{cell(row.get('label') or labels[row['name']])}**"
                lines.append(f"| {md_cell(field)} | {md_cell(row['value'])} |")
            lines.append("")
        for block in example.get("code") or []:
            lines += [f"**{cell(labels[block['for']])}**", ""]
            lines += fenced(block["text"], block.get("lang")) + [""]
        results = example.get("results") or []
        if results:
            lines += ["The task returns:", "", "| Result | Value |", "| --- | --- |"]
            for row in results:
                lines.append(f"| {code(row['name'])} | {md_cell(row['value'])} |")
            lines.append("")
        if (example.get("outcome") or "").strip():
            lines += [example["outcome"].strip(), ""]

    problems = [p for p in usage.get("errors") or []
                if gated(p, default_image, slug, "problem", skipped)]
    if problems:
        lines += ["### Common problems", "", "| Symptom | Cause | Fix |", "| --- | --- | --- |"]
        for p in problems:
            lines.append(f"| {md_cell(p['symptom'])} | {md_cell(p['cause'])} | {md_cell(p['fix'])} |")
        lines.append("")
    return lines


def frontmatter(title, order, description, tag, sidebar=None):
    lines = ["---", f"title: {title}"]
    if sidebar:
        lines.append(f"sidebarTitle: {sidebar}")
    return lines + [f"order: {order}", f"description: {description}", f'verified: "{tag}"', "---", ""]


def alert(level, text):
    """A GitHub alert: the marker on its own line, then every line of the text quoted."""
    kind = "WARNING" if level == "warning" else "NOTE"
    body = [f"> {line}" if line.strip() else ">" for line in text.strip().split("\n")]
    return [f"> [!{kind}]"] + body + [""]


def marker(tag):
    return f"{MARKER} from flow.service.workflow {tag}. Don't edit by hand. -->"


def count_phrase(n, word="task"):
    return f"{n} {word}" + ("" if n == 1 else "s")


def render_category(category, order, items, notes, tag, default_image, artifact_image,
                    applied, skipped, used):
    shown = [i for i in items if in_palette(i)]
    hidden = [i for i in items if not in_palette(i)]
    lines = frontmatter(
        category, order,
        f"The {category} tasks in the Flow catalogue, with each task's parameters, results and image.",
        tag,
    )
    lines += [marker(tag), "", f"# {category}", ""]
    intro = f"The {category} category has {count_phrase(len(items))}"
    if hidden:
        intro += f": {len(shown)} in the palette and {len(hidden)} that isn't"
    intro += (
        ". Each entry shows the task's latest revision, the one the palette adds."
        " See [Reading an entry](./overview#reading-an-entry)."
    )
    lines += [intro, ""]
    page_note = notes.get("categories", {}).get(category, {}).get("page")
    if page_note:
        lines += alert(notes["categories"][category].get("level", "note"), page_note)

    for item in shown:
        slug = item["task"]["name"]
        task_notes = notes_for(slug, item, notes, default_image, applied, skipped)
        lines += render_task(item, task_notes, artifact_image)
        usage = notes.get("usage", {}).get(slug)
        if usage:
            lines += render_usage(slug, usage, item, default_image, skipped)
            used.append(slug)

    if hidden:
        lines += [
            "## Not in the palette",
            "",
            "These tasks are in the catalogue, but the palette doesn't list them because they"
            " aren't active. Admins see them in **Admin › Tasks**.",
            "",
            "| Task | Slug | Status | Revision | Description |",
            "| --- | --- | --- | --- | --- |",
        ]
        for item in hidden:
            latest = item["latest"]
            lines.append(
                f"| {cell(latest['displayName'])} | {code(item['task']['name'])} | "
                f"{code(item['task'].get('status', ''))} | {latest['version']} | "
                f"{cell(latest.get('description'))} |"
            )
        lines.append("")
        for item in hidden:
            for note in notes_for(item["task"]["name"], item, notes, default_image, applied, skipped):
                lines += alert("note", f"{item['latest']['displayName']}: {note['text']}")
    return "\n".join(lines).rstrip() + "\n"


def render_overview(ordered, grouped, notes, tag, default_image):
    total = sum(len(grouped[c]) for c in ordered)
    shown = sum(1 for c in ordered for i in grouped[c] if in_palette(i))
    lines = frontmatter(
        "Task catalogue", 1,
        "The tasks Flow ships in its catalogue, by palette category, and how to read each entry.",
        tag, sidebar="Overview",
    )
    lines += [marker(tag), "", "# Task catalogue", ""]
    intro = (
        f"The catalogue is the set of global tasks Flow seeds, available in every workspace:"
        f" {total} tasks in {len(ordered)} categories."
    )
    if total - shown == 1:
        intro += f" The palette lists {shown} of them; the other one isn't active."
    elif total != shown:
        intro += f" The palette lists {shown} of them; the other {total - shown} aren't active."
    intro += (
        " Each category page lists its tasks with their parameters, results and image, at the"
        " latest revision. For what a task is and how revisions work, see"
        " [Tasks](../fundamentals/tasks)."
    )
    lines += [
        intro,
        "",
        "The categories are in palette order: **Workflow** first, then the rest A to Z.",
        "",
        "| Category | Tasks | In the palette |",
        "| --- | --- | --- |",
    ]
    for category in ordered:
        items = grouped[category]
        names = " · ".join(cell(i["latest"]["displayName"]) for i in items if in_palette(i))
        hidden = [i for i in items if not in_palette(i)]
        if hidden:
            names += " (not in the palette: " + ", ".join(
                cell(i["latest"]["displayName"]) for i in hidden) + ")"
        lines.append(f"| [{cell(category)}](./{page_slug(category)}) | {len(items)} | {names} |")
    lines.append("")

    for category, category_notes in notes.get("categories", {}).items():
        if category_notes.get("overview"):
            lines += alert("note", category_notes["overview"])

    lines += [
        "## Reading an entry",
        "",
        "Each task shows its latest revision, which is the one the palette adds to a new node."
        " A saved node stays on its revision until you upgrade it in the editor.",
        "",
        "- **Slug:** the task's unique name.",
        "- **Type:** decides who runs the task: a dispatcher, or Flow itself. See"
        " [Task types](../fundamentals/tasks#task-types).",
        "- **Revision:** the latest revision's number.",
        "- **Image:** the container image the task runs on. \"Default task image\" means the"
        " image in **Admin › Settings › Tasks › Default Image Path**"
        + (f", seeded as `{default_image}`." if default_image else "."),
        "- **Parameters:** the fields you fill in on the node. The label is the one the editor"
        " shows. **Secured** is a Password field: Flow stores its value encrypted, reads it back"
        " as `*****` and scrubs it from logs. A secured field's default is shown only when it's a"
        " parameter reference, such as `$(workspace.params.github-token)`. See"
        " [Credentials in catalogue tasks](../fundamentals/tasks#credentials-in-catalogue-tasks).",
        "- **Results:** the values a later task reads as `$(tasks.<name>.results.<result>)`.",
    ]
    if notes.get("usage"):
        lines.append(
            "- **Example** and **Common problems:** for the most-used tasks, the fields you'd set"
            " for a typical job and what the task returns, then the failures people hit most, each"
            " with its cause and fix."
        )
    lines.append("")
    return "\n".join(lines).rstrip() + "\n"


