#!/usr/bin/env python3
"""Generate the Boomerang Flow task catalogue pages from flow.service.workflow's seed at a tag.

Reads, with `git show <tag>:<path>`:
  - service-core/src/main/resources/seed/tasks.json and task-revisions.json (the catalogue);
  - service-core/src/main/resources/seed/settings.json (the default task image);
  - service-dispatcher/src/main/resources/application.properties (the artifact task image).

Tasks that only a migration adds are listed by hand in notes.json, with the hand-kept notes and
the most-used tasks' examples and common problems ("usage").
Writes flow/catalogue/overview.md and one page per palette category. flow/catalogue/index.md is
frontmatter only and hand-kept. See tools/catalogue/README.md.

Python 3.9+, standard library only.
"""

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

DOCS_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUT = DOCS_ROOT / "flow" / "catalogue"
DEFAULT_NOTES = Path(__file__).resolve().parent / "notes.json"

SEED_DIR = "service-core/src/main/resources/seed"
TASKS_PATH = f"{SEED_DIR}/tasks.json"
REVISIONS_PATH = f"{SEED_DIR}/task-revisions.json"
SETTINGS_PATH = f"{SEED_DIR}/settings.json"
DISPATCHER_PROPERTIES = "service-dispatcher/src/main/resources/application.properties"

MARKER = "<!-- Generated by tools/catalogue/generate.py"

# The palette lists this category first, then the rest by JavaScript `<` comparison
# (client-web/src/Features/WorkflowEditor/Designer/Tasks/Tasks.tsx).
FIRST_CATEGORY = "workflow"

# Types Flow runs itself, with no container (specifications/dispatcher-contract.md).
ENGINE_TYPES = {
    "acquirelock", "releaselock", "approval", "manual", "runworkflow", "runscheduledworkflow",
    "setwfproperty", "setwfstatus", "sleep", "decision", "eventwait",
}
# Types that take the default task image when the revision names none (engine/DAGUtility.java).
DEFAULT_IMAGE_TYPES = {"template", "script"}
ARTIFACT_TYPES = {"uploadartifact", "downloadartifact"}

# Field type names as Task Manager shows them (client-web/src/Features/TaskManager/constants.tsx,
# client-web/src/Constants/index.ts). A password field is shown as "Secured".
FIELD_TYPES = {
    "boolean": "Boolean",
    "email": "Email",
    "number": "Number",
    "password": "Secured",
    "select": "Select",
    "slider": "Slider",
    "string": "String",
    "text": "Text",
    "textarea": "Text Area",
    "texteditor": "Text Editor",
    "texteditor::shell": "Text Editor - Shell",
    "texteditor::text": "Text Editor - Text",
    "texteditor::yaml": "Text Editor - YAML",
    "texteditor::javascript": "Text Editor - JavaScript/JSON",
    "time": "Time",
    "url": "URL",
}

# A secured default is shown only when it is a parameter reference, never a literal value.
PARAM_REFERENCE = re.compile(r"\$\([A-Za-z0-9_.\-]+\)")


class CatalogueError(Exception):
    pass


# ---------------------------------------------------------------------------------------------
# Reading the source


def git_show(repo, tag, path):
    result = subprocess.run(
        ["git", "-C", str(repo), "show", f"{tag}:{path}"],
        capture_output=True, text=True,
    )
    if result.returncode != 0:
        raise CatalogueError(f"git show {tag}:{path} failed: {result.stderr.strip()}")
    return result.stdout


def git_has(repo, tag, path):
    result = subprocess.run(
        ["git", "-C", str(repo), "cat-file", "-e", f"{tag}:{path}"],
        capture_output=True, text=True,
    )
    return result.returncode == 0


def documents(text, path):
    data = json.loads(text)
    if not isinstance(data, dict) or not isinstance(data.get("documents"), list):
        raise CatalogueError(f"{path}: expected {{\"documents\": [...]}}")
    return data["documents"]


def find_key(node, key):
    """The value of the first {"key": key, "value": ...} object anywhere in a JSON tree."""
    if isinstance(node, dict):
        if node.get("key") == key and "value" in node:
            return node["value"]
        children = node.values()
    elif isinstance(node, list):
        children = node
    else:
        return None
    for child in children:
        found = find_key(child, key)
        if found is not None:
            return found
    return None


def property_value(text, key):
    for line in text.splitlines():
        line = line.strip()
        if line.startswith(key) and line[len(key):].lstrip().startswith("="):
            return line.split("=", 1)[1].strip()
    return None


def load_catalogue(repo, tag, notes, warnings):
    """Every catalogue task with its revisions: {slug: {"task": {...}, "revisions": [...]}}."""
    tasks = documents(git_show(repo, tag, TASKS_PATH), TASKS_PATH)
    revisions = documents(git_show(repo, tag, REVISIONS_PATH), REVISIONS_PATH)

    catalogue = {}
    for task in tasks:
        name = task.get("name")
        if not name:
            raise CatalogueError(f"{TASKS_PATH}: a task has no name")
        if name in catalogue:
            raise CatalogueError(f"{TASKS_PATH}: task {name} appears twice")
        catalogue[name] = {"task": task, "revisions": [], "source": TASKS_PATH}

    for revision in revisions:
        parent = revision.get("parentRef")
        if parent not in catalogue:
            raise CatalogueError(f"{REVISIONS_PATH}: revision of unknown task {parent!r}")
        catalogue[parent]["revisions"].append(revision)

    for entry in notes.get("migrationTasks", []):
        task, revision, source = entry["task"], entry["revision"], entry["source"]
        name = task["name"]
        if name in catalogue:
            warnings.append(
                f"{name} is now in {TASKS_PATH}; the seed is used. Remove it from migrationTasks."
            )
            continue
        check_migration_entry(repo, tag, entry, warnings)
        catalogue[name] = {
            "task": task,
            "revisions": [dict(revision, parentRef=name)],
            "source": source,
        }

    for name, item in catalogue.items():
        if not item["revisions"]:
            raise CatalogueError(f"task {name} has no revisions")
        versions = [r.get("version") for r in item["revisions"]]
        if len(set(versions)) != len(versions):
            raise CatalogueError(f"task {name} has two revisions with the same version")
        item["revisions"].sort(key=lambda r: r["version"])
        item["latest"] = item["revisions"][-1]
    return catalogue


def check_migration_entry(repo, tag, entry, warnings):
    """Warn when a hand-listed migration task no longer matches its migration's source."""
    source, name = entry["source"], entry["task"]["name"]
    if not git_has(repo, tag, source):
        warnings.append(f"{name}: {source} is not in {tag}. Check migrationTasks.")
        return
    java = git_show(repo, tag, source)
    params = entry["revision"].get("spec", {}).get("params") or []
    results = entry["revision"].get("spec", {}).get("results") or []
    expected = [name, entry["task"]["type"], entry["revision"]["displayName"]]
    expected += [p["name"] for p in params] + [p["label"] for p in params]
    expected += [r["name"] for r in results]
    for value in expected:
        if f'"{value}"' not in java:
            warnings.append(f"{name}: \"{value}\" is not in {source} at {tag}. Re-read it by hand.")


